/* ---------- SQL literal helpers ---------- */
const q = (v: string | null | undefined) => (v === null || v === undefined ? 'null' : `'${v.replace(/'/g, "''")}'`);
const arr = (xs: string[]) => (xs.length ? `array[${xs.map((x) => q(x)).join(', ')}]::text[]` : `array[]::text[]`);
const js = (o: unknown) => `'${JSON.stringify(o).replace(/'/g, "''")}'::jsonb`;
const n = (v: number | null | undefined) => (v === null || v === undefined ? 'null' : String(v));
const status = (s: 'published' | 'under-review') => (s === 'published' ? 'published' : 'under_review');
const slugify = (s: string) =>
  s.normalize('NFD').replace(/[̀-ͯ]/g, '').toLowerCase().replace(/&/g, ' and ').replace(/[^a-z0-9]+/g, '-').replace(/^-+|-+$/g, '');

const out: string[] = [];
const emit = (s = '') => out.push(s);

const TRADITION = `(select id from public.traditions where slug = 'sanatan-dharma')`;
const bySlug = (table: string, slug: string) => `(select id from public.${table} where slug = ${q(slug)})`;
const cls = (slug: string) => `(select id from public.classifications where tradition_id = ${TRADITION} and slug = ${q(slug)})`;
const classSlug: Record<string, string> = {
  Shruti: 'shruti', Smriti: 'smriti', Itihasa: 'itihasa', Purana: 'purana',
  'Darshana literature': 'darshana-literature', 'Yoga & devotional literature': 'yoga-devotional-literature',
};

emit('-- GENERATED by scripts/export-seed.ts from lib/content and lib/learning. Do not edit by hand.');
emit('-- Re-generate with: npm run db:seed');
emit('begin;');
emit(`set local dq.skip_audit = 'on';`);
emit();

/* ---------- traditions & classifications ---------- */
emit('-- Traditions: Sanatan Dharma is active. The others are placeholders only (no content, hidden by RLS).');
const traditions = [
  ['sanatan-dharma', 'Sanatan Dharma', 'Scriptures, philosophies and wisdom traditions of Sanatan Dharma.', 'active'],
  ['islam', 'Islam', 'Planned. No content yet. Will be presented in its own terms, separate from other traditions.', 'planned'],
  ['christianity', 'Christianity', 'Planned. No content yet. Will be presented in its own terms, separate from other traditions.', 'planned'],
  ['judaism', 'Judaism', 'Planned. No content yet. Will be presented in its own terms, separate from other traditions.', 'planned'],
  ['buddhism', 'Buddhism', 'Planned. No content yet. Will be presented in its own terms, separate from other traditions.', 'planned'],
];
for (const [slug, name, desc, st] of traditions) {
  emit(`insert into public.traditions (slug, name, description, status) values (${q(slug)}, ${q(name)}, ${q(desc)}, ${q(st)})
  on conflict (slug) do update set name = excluded.name, description = excluded.description, status = excluded.status;`);
}
const classifications: [string, string, string][] = [
  ['shruti', 'Shruti', '“That which is heard”: the Vedic corpus.'],
  ['smriti', 'Smriti', '“That which is remembered”: tradition-based texts.'],
  ['itihasa', 'Itihasa', 'The two great epics: Ramayana and Mahabharata.'],
  ['purana', 'Purana', 'Texts of cosmology, genealogy, legend and devotional teaching.'],
  ['darshana-literature', 'Darshana literature', 'Foundational works of the classical schools of philosophy.'],
  ['yoga-devotional-literature', 'Yoga & devotional literature', 'Texts on the theory and practice of yoga, meditation and devotion.'],
];
for (const [slug, label, d] of classifications) {
  emit(`insert into public.classifications (tradition_id, slug, label, description) values (${TRADITION}, ${q(slug)}, ${q(label)}, ${q(d)})
  on conflict (tradition_id, slug) do update set label = excluded.label, description = excluded.description;`);
}
emit();

/* ---------- sources ---------- */
emit('-- Sources. Nothing below is marked verified unless it has been checked.');
type Src = { slug: string; kind: string; title: string; creators?: string[]; license: string; licenseNotes?: string; url?: string; verified?: boolean; verifiedOn?: string; notes?: string };
const sources: Src[] = [
  { slug: 'bg-sanskrit-standard', kind: 'primary_text', title: 'Bhagavad Gita, standard Sanskrit text', creators: ['Traditionally attributed to Vyasa'], license: 'public_domain',
    verified: true, verifiedOn: '2026-11-19', notes: 'Verse numbering, per-chapter verse counts and the text of verse 2.47 were cross-checked against a public-domain Sanskrit edition.' },
  { slug: 'gita-json-dataset', kind: 'dataset', title: 'gita/gita Bhagavad Gita JSON dataset', url: 'https://github.com/gita/gita', license: 'unknown',
    licenseNotes: 'The repository code is under the Unlicense, but its translations and word meanings are copyrighted. Used only to verify verse numbering and the Sanskrit text. No translation or word meaning from it is used.' },
  { slug: 'dharmaquest-editorial', kind: 'editorial', title: 'DharmaQuest editorial', license: 'editorial',
    notes: 'Summaries, word glosses, lesson text and explanations written by DharmaQuest. Not translations and not traditional commentary.' },
];
for (const r of FURTHER_READING) {
  const i = r.indexOf(', ');
  const creators = r.slice(0, i).replace(/ \(eds\.\)/, '').split(/ and /);
  const title = r.slice(i + 2);
  sources.push({ slug: slugify(title), kind: 'scholarly_work', title, creators, license: 'unknown', notes: 'Further reading for the Darshana summaries. Not reproduced on the site.' });
}
for (const s of sources) {
  emit(`insert into public.content_sources (slug, kind, title, creators, license, license_notes, url, verified, verified_on, notes)
  values (${q(s.slug)}, ${q(s.kind)}::public.source_kind, ${q(s.title)}, ${arr(s.creators ?? [])}, ${q(s.license)}::public.license_kind, ${q(s.licenseNotes)}, ${q(s.url)}, ${s.verified ? 'true' : 'false'}, ${s.verifiedOn ? `date ${q(s.verifiedOn)}` : 'null'}, ${q(s.notes)})
  on conflict (slug) do update set kind = excluded.kind, title = excluded.title, creators = excluded.creators, license = excluded.license,
    license_notes = excluded.license_notes, url = excluded.url, verified = excluded.verified, verified_on = excluded.verified_on, notes = excluded.notes;`);
}
emit();

