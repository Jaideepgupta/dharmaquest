/**
 * Generates supabase/seed.sql from the TypeScript content modules, so the database and the
 * site are built from one source of truth. Run: npm run db:seed
 * The output is deterministic and idempotent (safe to run repeatedly).
 */
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
